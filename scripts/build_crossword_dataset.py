def normalize_answer(text: str) -> str:
    text = unicodedata.normalize("NFC", text.strip().upper())
    text = text.replace(" ", "")
    return text


def answer_cells(answer: str) -> list[str]:
    """One cell per Unicode letter; CH is two cells (C + H)."""
    return list(normalize_answer(answer))


def tajenka_letters(phrase: str) -> list[str]:
    return [ch for ch in unicodedata.normalize("NFC", phrase.strip().upper()) if not ch.isspace()]


def main() -> None:
    clues_raw = [c for c in RAW_CLUES if c[0] not in SKIP_ANSWERS] + [
        c for c in EXTRA_CLUES if c[0] not in SKIP_EXTRA and c[0] not in SKIP_ANSWERS
    ]

    # Deduplicate by normalized answer (keep first good clue)
    seen: set[str] = set()
    clues: list[dict] = []
    for answer, clue, themes, diffs in clues_raw:
        ans = normalize_answer(answer)
        if not ans or ans in seen:
            continue
        # Answers must be letters only (Czech alphabet incl. diacritics)
        if not all(ch in ALLOWED for ch in ans):
            continue
        if len(ans) < 2 or len(ans) > 14:
            continue
        # Drop nonsense / broken
        if "—" in clue or "správně" in clue or "pozor" in clue.lower() or "nepoužívat" in clue:
            continue
        seen.add(ans)
        clues.append(
            {
                "answer": ans,
                "clue": clue.strip(),
                "themes": sorted(set(themes)),
                "difficulty": diffs,
            }
        )

    tajenky: list[dict] = []
    seen_t: set[str] = set()
    skip_phrases = {
        "FAIR PLAY",
        "FAIRPLAY",
        "OSTÝ VÍTR",
        "ÚSMĚV NESTAČÍ",
        "ZLATA RYBA",
        "TIŠÍ SEN",
        "FÉROVÁ HRA",  # accented foreign-ish
    }
    for phrase, themes, diffs in TAJENKY:
        phrase_n = unicodedata.normalize("NFC", phrase.strip().upper())
        # collapse spaces for identity but keep display with single spaces
        parts = phrase_n.split()
        display = " ".join(parts)
        letters = "".join(parts)
        if display in skip_phrases or letters in seen_t:
            continue
        if not all(ch.isalpha() or ch.isspace() for ch in display):
            continue
        n_letters = len(letters)
        if n_letters < 5 or n_letters > 14:
            continue
        seen_t.add(letters)
        tajenky.append(
            {
                "phrase": display,
                "themes": sorted(set(themes)),
                "difficulty": diffs,
            }
        )

    payload = {
        "version": "1.0.0",
        "language": "cs",
        "themes": THEMES,
        "clues": clues,
        "tajenky": tajenky,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        yaml.safe_dump(payload, allow_unicode=True, sort_keys=False, width=100),
        encoding="utf-8",
    )
    print(f"Wrote {OUT}")
    print(f"Clues: {len(clues)}, tajenky: {len(tajenky)}")
    # Letter coverage check
    letters = set()
    for c in clues:
        letters.update(answer_cells(c["answer"]))
    needed = set()
    for t in tajenky:
        needed.update(tajenka_letters(t["phrase"]))
    missing = sorted(needed - letters)
    print(f"Unique answer letters: {len(letters)}")
    print(f"Tajenka letters missing from answers: {missing or 'none'}")


if __name__ == "__main__":
    main()
